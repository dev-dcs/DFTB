    /** Credits grouped in [BundleKind] declaration order; kinds with no entries are omitted. */
    fun groupedByKind(): Map<BundleKind, List<OpenSourceCredit>> =
        BundleKind.entries
            .associateWith { kind -> all.filter { it.bundledAs == kind } }
            .filterValues { it.isNotEmpty() }

    /** Lookup by [OpenSourceCredit.id], e.g. for a deep link from a settings row. */
    fun byId(id: String): OpenSourceCredit? = all.firstOrNull { it.id == id }

    /** Distinct licenses in use, in first-appearance order, for a "licenses" summary section. */
    fun licenses(): List<OssLicense> = all.map { it.license }.distinct()
