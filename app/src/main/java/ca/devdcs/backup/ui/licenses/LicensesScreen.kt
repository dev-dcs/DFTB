/**
 * Stand-alone destination for the open-source credits, reachable from Settings > About once that
 * screen exists. Renders exactly the same list as onboarding step 4 so attribution never drifts
 * between the two places it is shown.
 */
@Composable
fun LicensesScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val snackbarHostState = remember { SnackbarHostState() }
    val noBrowserMessage = stringResource(R.string.onboarding_no_app_for_link)
    var expandedIds by rememberSaveable(stateSaver = ExpandedCreditIdsSaver) { mutableStateOf(emptySet()) }

    val scrollBehavior = TopAppBarDefaults.pinnedScrollBehavior(rememberTopAppBarState())

    Scaffold(
        modifier = Modifier.nestedScroll(scrollBehavior.nestedScrollConnection),
        topBar = {
            TopAppBar(
                title = { Text(stringResource(R.string.licenses_title)) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(
                            Icons.AutoMirrored.Filled.ArrowBack,
                            contentDescription = stringResource(R.string.onboarding_back),
                        )
                    }
                },
                scrollBehavior = scrollBehavior,
            )
        },
        snackbarHost = { SnackbarHost(snackbarHostState) },
    ) { innerPadding ->
        val layoutDirection = LocalLayoutDirection.current
        LazyColumn(
            modifier = Modifier.fillMaxSize(),
            contentPadding = PaddingValues(
                start = innerPadding.calculateStartPadding(layoutDirection) + 16.dp,
                end = innerPadding.calculateEndPadding(layoutDirection) + 16.dp,
                top = innerPadding.calculateTopPadding() + 4.dp,
                bottom = innerPadding.calculateBottomPadding() + 24.dp,
            ),
            verticalArrangement = Arrangement.spacedBy(8.dp),
        ) {
            openSourceCreditItems(
                expandedIds = expandedIds,
                onToggle = { id -> expandedIds = if (id in expandedIds) expandedIds - id else expandedIds + id },
                onOpenUrl = { url ->
                    if (!ExternalLinks.openUrl(context, url)) {
                        scope.launch { snackbarHostState.showSnackbar(noBrowserMessage) }
                    }
                },
            )
        }
    }
}
