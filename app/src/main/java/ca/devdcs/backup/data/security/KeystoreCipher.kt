package ca.devdcs.backup.data.security

import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyInfo
import android.security.keystore.KeyPermanentlyInvalidatedException
import android.security.keystore.KeyProperties
import ca.devdcs.backup.core.logging.DftbLog
import ca.devdcs.backup.domain.security.VaultException
import java.security.GeneralSecurityException
import java.security.KeyStore
import java.security.ProviderException
import java.security.UnrecoverableKeyException
import javax.crypto.AEADBadTagException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.SecretKeyFactory
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-256-GCM sealed by a non-exportable key living in AndroidKeyStore (StrongBox when the device
 * has one, TEE otherwise). Because the key never leaves the secure hardware, vault files are
 * useless when copied to another device or extracted from an app-data backup: that device binding
 * is the whole point of the vault, not a limitation to work around.
 *
 * The master key is generated once, lazily, and never regenerated by this class. If the Keystore
 * reports it invalidated or unrecoverable, every stored secret is already lost; a fresh key would
 * only hide that fact, so the failure is surfaced as a [VaultException] for the UI to explain.
 *
 * A new [Cipher] instance is created per call: Cipher objects are not thread-safe, and the
 * Keystore must pick the nonce itself (randomised encryption), so no IV is ever supplied on encrypt.
 */
class KeystoreCipher : VaultCipher {

    private val keyLock = Any()

    @Volatile
    private var cachedKey: SecretKey? = null

    override fun encrypt(plaintext: ByteArray, aad: ByteArray): EncryptedBlob {
        val cipher = newCipher()
        try {
            cipher.init(Cipher.ENCRYPT_MODE, masterKey())
            cipher.updateAAD(aad)
            val ciphertext = cipher.doFinal(plaintext)
            val iv = cipher.iv ?: throw VaultException(
                "Keystore returned no IV after encryption",
                reason = VaultException.Reason.KEYSTORE_UNAVAILABLE,
            )
            return EncryptedBlob(iv = iv, ciphertext = ciphertext)
        } catch (e: KeyPermanentlyInvalidatedException) {
            throw invalidated(e)
        } catch (e: GeneralSecurityException) {
            throw VaultException("Encryption failed", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        } catch (e: ProviderException) {
            throw VaultException("Keystore provider failed during encryption", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        }
    }

    override fun decrypt(blob: EncryptedBlob, aad: ByteArray): ByteArray {
        if (blob.iv.size != IV_LENGTH_BYTES) {
            throw VaultException(
                "Vault blob IV is ${blob.iv.size} bytes; GCM requires $IV_LENGTH_BYTES, so the blob is corrupt",
                reason = VaultException.Reason.CORRUPT_BLOB,
            )
        }
        val cipher = newCipher()
        try {
            cipher.init(Cipher.DECRYPT_MODE, masterKey(), GCMParameterSpec(TAG_LENGTH_BITS, blob.iv))
            cipher.updateAAD(aad)
            return cipher.doFinal(blob.ciphertext)
        } catch (e: KeyPermanentlyInvalidatedException) {
            throw invalidated(e)
        } catch (e: AEADBadTagException) {
            throw VaultException(
                "Authentication tag mismatch: the vault entry was modified or belongs to another ref",
                e,
                VaultException.Reason.INTEGRITY_FAILURE,
            )
        } catch (e: GeneralSecurityException) {
            throw VaultException("Decryption failed", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        } catch (e: ProviderException) {
            throw VaultException("Keystore provider failed during decryption", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        }
    }

    override fun masterKeyExists(): Boolean = try {
        openKeyStore().containsAlias(MASTER_KEY_ALIAS)
    } catch (e: GeneralSecurityException) {
        throw VaultException("Cannot query AndroidKeyStore", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
    }

    /** Where the master key lives; shown in diagnostics so users know their vault is hardware-backed. */
    fun masterKeyInfo(): MasterKeyInfo {
        val key = masterKey()
        return try {
            val factory = SecretKeyFactory.getInstance(key.algorithm, PROVIDER)
            val info = factory.getKeySpec(key, KeyInfo::class.java) as KeyInfo
            val level = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
                when (info.securityLevel) {
                    KeyProperties.SECURITY_LEVEL_STRONGBOX -> MasterKeyInfo.SecurityLevel.STRONGBOX
                    KeyProperties.SECURITY_LEVEL_TRUSTED_ENVIRONMENT -> MasterKeyInfo.SecurityLevel.TRUSTED_ENVIRONMENT
                    KeyProperties.SECURITY_LEVEL_UNKNOWN_SECURE -> MasterKeyInfo.SecurityLevel.SECURE_UNSPECIFIED
                    KeyProperties.SECURITY_LEVEL_SOFTWARE -> MasterKeyInfo.SecurityLevel.SOFTWARE
                    else -> MasterKeyInfo.SecurityLevel.UNKNOWN
                }
            } else {
                legacySecurityLevel(info)
            }
            MasterKeyInfo(alias = MASTER_KEY_ALIAS, securityLevel = level)
        } catch (e: GeneralSecurityException) {
            DftbLog.w(TAG, "Could not inspect master key", e)
            MasterKeyInfo(alias = MASTER_KEY_ALIAS, securityLevel = MasterKeyInfo.SecurityLevel.UNKNOWN)
        }
    }

    /** Pre-Android 12 devices only expose the coarse secure-hardware flag. */
    @Suppress("DEPRECATION")
    private fun legacySecurityLevel(info: KeyInfo): MasterKeyInfo.SecurityLevel =
        if (info.isInsideSecureHardware) MasterKeyInfo.SecurityLevel.SECURE_UNSPECIFIED else MasterKeyInfo.SecurityLevel.SOFTWARE

    private fun newCipher(): Cipher = try {
        Cipher.getInstance(TRANSFORMATION)
    } catch (e: GeneralSecurityException) {
        throw VaultException("$TRANSFORMATION is unavailable on this device", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
    }

    private fun masterKey(): SecretKey {
        cachedKey?.let { return it }
        synchronized(keyLock) {
            cachedKey?.let { return it }
            val key = loadExistingKey() ?: generateKey()
            cachedKey = key
            return key
        }
    }

    private fun loadExistingKey(): SecretKey? {
        val keyStore = openKeyStore()
        val present = try {
            keyStore.containsAlias(MASTER_KEY_ALIAS)
        } catch (e: GeneralSecurityException) {
            throw VaultException("Cannot query AndroidKeyStore", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        }
        if (!present) return null
        return try {
            keyStore.getKey(MASTER_KEY_ALIAS, null) as? SecretKey
                ?: throw VaultException(
                    "Vault master key alias holds an unexpected key type",
                    reason = VaultException.Reason.KEY_UNRECOVERABLE,
                )
        } catch (e: UnrecoverableKeyException) {
            throw VaultException(
                "Vault master key exists but cannot be loaded; stored secrets are unrecoverable on this device",
                e,
                VaultException.Reason.KEY_UNRECOVERABLE,
            )
        } catch (e: GeneralSecurityException) {
            throw VaultException("Cannot load vault master key", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        }
    }

    private fun generateKey(): SecretKey {
        return try {
            generateKey(strongBox = true).also { DftbLog.i(TAG, "Vault master key generated in StrongBox") }
        } catch (e: ProviderException) {
            // StrongBoxUnavailableException is the clean signal, but some devices advertise StrongBox
            // and then throw a plain ProviderException while generating in it; fall back either way.
            DftbLog.i(TAG, "StrongBox key generation failed (${e.javaClass.simpleName}), generating vault master key in TEE/software Keystore")
            try {
                generateKey(strongBox = false)
            } catch (inner: GeneralSecurityException) {
                throw VaultException("Cannot generate vault master key", inner, VaultException.Reason.KEYSTORE_UNAVAILABLE)
            } catch (inner: ProviderException) {
                throw VaultException("Keystore refused to generate vault master key", inner, VaultException.Reason.KEYSTORE_UNAVAILABLE)
            }
        } catch (e: GeneralSecurityException) {
            throw VaultException("Cannot generate vault master key", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
        }
    }

    private fun generateKey(strongBox: Boolean): SecretKey {
        val spec = KeyGenParameterSpec.Builder(
            MASTER_KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(KEY_SIZE_BITS)
            .setRandomizedEncryptionRequired(true)
            .setUserAuthenticationRequired(false)
            .apply { if (strongBox) setIsStrongBoxBacked(true) }
            .build()
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        generator.init(spec)
        return generator.generateKey()
    }

    private fun openKeyStore(): KeyStore = try {
        KeyStore.getInstance(PROVIDER).apply { load(null) }
    } catch (e: GeneralSecurityException) {
        throw VaultException("AndroidKeyStore is unavailable", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
    } catch (e: java.io.IOException) {
        throw VaultException("AndroidKeyStore failed to load", e, VaultException.Reason.KEYSTORE_UNAVAILABLE)
    }

    private fun invalidated(cause: KeyPermanentlyInvalidatedException): VaultException {
        cachedKey = null
        return VaultException(
            "Vault master key was permanently invalidated by the system; stored secrets cannot be recovered",
            cause,
            VaultException.Reason.KEY_INVALIDATED,
        )
    }

    /** Diagnostic snapshot of the master key's protection. */
    data class MasterKeyInfo(
        val alias: String,
        val securityLevel: SecurityLevel,
    ) {
        /** Where the key material is held; anything but SOFTWARE/UNKNOWN means it cannot be extracted from the device. */
        enum class SecurityLevel { STRONGBOX, TRUSTED_ENVIRONMENT, SECURE_UNSPECIFIED, SOFTWARE, UNKNOWN }
    }

    companion object {
        const val MASTER_KEY_ALIAS = "dftb.vault.master.v1"
        const val TAG_LENGTH_BITS = 128
        private const val IV_LENGTH_BYTES = 12
        private const val KEY_SIZE_BITS = 256
        private const val PROVIDER = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val TAG = "VaultCipher"
    }
}
